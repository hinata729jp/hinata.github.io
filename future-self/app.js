  var AXIS_META = [
    { key: "C", left: "安定", right: "変化", scale: 18 },
    { key: "S", left: "社会的成功", right: "個人的充実", scale: 15 },
    { key: "R", left: "独立", right: "協働", scale: 18 },
    { key: "T", left: "専門深化", right: "越境拡張", scale: 14 },
    { key: "K", left: "堅実", right: "挑戦", scale: 15 },
  ];

  // 診断を受けていない状態（共有リンク・相性カード・サンプル閲覧）でタイプコードだけから
  // それらしいスコアを仮組みする。各軸の傾き方向のみコードから読み取り、大きさは代表値で固定。
  function representativeScores(code) {
    var s = {};
    AXIS_META.forEach(function (axis, i) {
      var ch = code.charAt(i);
      s[axis.key] = (ch === axis.key) ? axis.scale * 0.6 : -axis.scale * 0.6;
    });
    return s;
  }

  function normalizeAxisPercent(score, axisMeta) {
    var pct = 50 + (score / axisMeta.scale) * 50;
    return Math.max(4, Math.min(96, pct));
  }

  function buildAxisBarsHtml(scores) {
    var rows = AXIS_META.map(function (axis) {
      var pct = normalizeAxisPercent(scores[axis.key], axis);
      var fillLeft = Math.min(50, pct);
      var fillWidth = Math.abs(pct - 50);
      var leaningRight = pct >= 50;
      return (
        '<div class="axis-row">' +
        '<span class="axis-pole-label left' + (leaningRight ? "" : " active") + '">' + axis.left + "</span>" +
        '<div class="axis-bar-track">' +
        '<div class="axis-bar-center"></div>' +
        '<div class="axis-bar-fill" style="left:' + fillLeft + "%;width:" + fillWidth + '%;"></div>' +
        '<div class="axis-bar-dot" style="left:' + pct + '%;"></div>' +
        "</div>" +
        '<span class="axis-pole-label right' + (leaningRight ? " active" : "") + '">' + axis.right + "</span>" +
        "</div>"
      );
    }).join("");
    return '<div class="axis-chart">' + rows + "</div>";
  }

  // ===== 状態 =====
  var state = {
    currentQuestion: 0,
    answers: [],
    resultCode: null,
    mbtiType: null,
    scores: null,
    scoresCode: null,
  };

  // ===== DOM参照 =====
  var $home = document.getElementById("screen-home");
  var $diagnose = document.getElementById("screen-diagnose");
  var $result = document.getElementById("screen-result");
  var $toast = document.getElementById("toast");

  function showScreen(name) {
    [$home, $diagnose, $result].forEach(function (el) { el.classList.add("hidden"); });
    if (name === "home") $home.classList.remove("hidden");
    if (name === "diagnose") $diagnose.classList.remove("hidden");
    if (name === "result") $result.classList.remove("hidden");
    window.scrollTo(0, 0);
  }

  function toast(msg) {
    $toast.textContent = msg;
    $toast.classList.add("show");
    clearTimeout(toast._t);
    toast._t = setTimeout(function () { $toast.classList.remove("show"); }, 2200);
  }

  function copyText(str) {
    if (navigator.clipboard && navigator.clipboard.writeText) {
      navigator.clipboard.writeText(str).catch(function () { fallbackCopy(str); });
    } else {
      fallbackCopy(str);
    }
  }

  function fallbackCopy(str) {
    var ta = document.createElement("textarea");
    ta.value = str;
    ta.style.position = "fixed";
    ta.style.opacity = "0";
    document.body.appendChild(ta);
    ta.select();
    try { document.execCommand("copy"); } catch (e) {}
    document.body.removeChild(ta);
  }

  // ===== ホーム画面 =====
  function renderHome() {
    var peek = document.getElementById("animal-peek");
    peek.innerHTML = "";
    Object.keys(TYPES).forEach(function (code) {
      var t = TYPES[code];
      var span = document.createElement("span");
      span.textContent = t.emoji;
      span.title = t.title;
      peek.appendChild(span);
    });

    var grid = document.getElementById("sample-grid");
    grid.innerHTML = "";
    PROTO_CODES.forEach(function (code) {
      var t = TYPES[code];
      var a = document.createElement("a");
      a.href = "?type=" + code;
      a.className = "sample-card";
      a.innerHTML = '<span class="emoji">' + t.emoji + '</span><span class="name">' + t.title + "</span>";
      a.addEventListener("click", function (e) {
        e.preventDefault();
        showResult(code);
        history.replaceState(null, "", "?type=" + code);
      });
      grid.appendChild(a);
    });
  }

  // ===== 診断画面 =====
  function startDiagnose() {
    state.currentQuestion = 0;
    state.answers = [];
    showScreen("diagnose");
    renderQuestion();
  }

  function renderQuestion() {
    var q = QUESTIONS[state.currentQuestion];
    document.getElementById("progress-current").textContent = state.currentQuestion + 1;
    var totalEl = document.getElementById("progress-total");
    if (totalEl) totalEl.textContent = QUESTIONS.length;
    document.getElementById("progress-fill").style.width =
      Math.round(((state.currentQuestion) / QUESTIONS.length) * 100) + "%";
    document.getElementById("question-text").textContent = q.text;

    var wrap = document.getElementById("options-wrap");
    wrap.innerHTML = "";

    if (q.isMbti) {
      var grid = document.createElement("div");
      grid.className = "mbti-type-grid";
      q.options.forEach(function (opt) {
        if (opt.mbti === null) return;
        var btn = document.createElement("button");
        btn.className = "mbti-type-btn";
        btn.type = "button";
        btn.textContent = opt.label;
        btn.addEventListener("click", function () { selectOption(opt); });
        grid.appendChild(btn);
      });
      wrap.appendChild(grid);
      var unknown = q.options.filter(function (o) { return o.mbti === null; })[0];
      if (unknown) {
        var uBtn = document.createElement("button");
        uBtn.className = "option-btn mbti-unknown-btn";
        uBtn.type = "button";
        uBtn.textContent = unknown.label;
        uBtn.addEventListener("click", function () { selectOption(unknown); });
        wrap.appendChild(uBtn);
      }
      return;
    }

    q.options.forEach(function (opt) {
      var btn = document.createElement("button");
      btn.className = "option-btn";
      btn.type = "button";
      btn.textContent = opt.label;
      btn.addEventListener("click", function () { selectOption(opt); });
      wrap.appendChild(btn);
    });
  }

  function selectOption(opt) {
    if (opt.mbti !== undefined) {
      state.mbtiType = opt.mbti;
    }
    state.answers.push(opt);
    if (state.currentQuestion < QUESTIONS.length - 1) {
      state.currentQuestion++;
      renderQuestion();
    } else {
      document.getElementById("progress-fill").style.width = "100%";
      var scores = computeScores(state.answers);
      var code = scoresToCode(scores);
      state.scores = scores;
      state.scoresCode = code;
      setTimeout(function () {
        showResult(code);
        history.replaceState(null, "", "?type=" + code);
      }, 250);
    }
  }

  // ===== 結果画面 =====
  function showResult(code) {
    state.resultCode = code;
    var type = TYPES[code];
    var result = RESULTS[code];

    if (!type) {
      code = PROTO_CODES[0];
      type = TYPES[code];
      result = RESULTS[code];
    }

    showScreen("result");

    var scores = (state.scoresCode === code && state.scores) ? state.scores : representativeScores(code);

    var html = "";
    html += '<div class="result-hero">';
    html += '  <div class="medallion">' + type.emoji + "</div>";
    html += '  <div class="badge-row"><span class="pill">' + type.element + '</span><span class="pill">10年後のあなた</span></div>';
    html += "  <h2>" + type.title + "</h2>";
    html += '  <div class="code">' + code + "</div>";
    html += '  <p class="one-liner">' + type.oneLiner + "</p>";
    html += '  <p class="ecology">' + result.ecology + "</p>";
    html += "</div>";

    html += section("📊", "あなたの5つの軸", buildAxisBarsHtml(scores));

    html += section("🔭", "10年後の情景", buildArtworkHtml(result.artwork) + "<p>" + result.future + "</p>");

    html += section("🔑", "未来を左右する3つのキーワード",
      '<div class="keyword-row">' + result.keywords.map(function (k) {
        return '<span class="keyword-badge">' + k + "</span>";
      }).join("") + "</div>");

    html += section("🧭", "3年以内の分岐点",
      '<div class="turning-point-box">' + result.turningPoint + "</div>");

    html += section("💎", "隠れた才能・気をつけたいこと",
      '<ul class="list-block strengths">' + result.strengths.map(li).join("") + "</ul>" +
      '<ul class="list-block cautions">' + result.cautions.map(li).join("") + "</ul>");

    html += section("💬", "あなたの相談スタイル",
      '<div class="consult-box"><p>' + result.consultingTendency + "</p>" +
      '<ul class="self-questions">' + result.selfQuestions.map(li).join("") + "</ul></div>");

    html += hinataCtaBlock(type, result, code);

    html += section("👣", "今日の一歩",
      '<div class="today-step-box">' + result.todayStep + "</div>");

    html += section("🤝", "相性の良い動物タイプ",
      '<div class="compat-row">' + result.compat.map(function (c) {
        var ct = TYPES[c];
        return '<a class="compat-card" href="?type=' + c + '" data-code="' + c + '"><span class="emoji">' + ct.emoji + '</span><span class="name">' + ct.title + "</span></a>";
      }).join("") + "</div>");

    html += retryBlock();

    html += '<footer class="foot-note">この診断は10年後のあなたを決めつけるものではなく、今の傾向をやさしく映すための一つの見方です。</footer>';

    $result.querySelector(".result-inner").innerHTML = html;

    // 相性カードのクリックをSPA内遷移に
    $result.querySelectorAll(".compat-card").forEach(function (a) {
      a.addEventListener("click", function (e) {
        e.preventDefault();
        var c = a.getAttribute("data-code");
        showResult(c);
        history.replaceState(null, "", "?type=" + c);
      });
    });

    wireHinataButtons(type, result);
    wireRetryButton();
  }

  function section(icon, title, bodyHtml) {
    return '<div class="section-block"><h3>' + icon + " " + title + "</h3>" + bodyHtml + "</div>";
  }

  function li(text) {
    return "<li>" + text + "</li>";
  }

  function buildArtworkHtml(artwork) {
    if (!artwork) return "";
    return (
      '<div class="artwork-wrap">' +
      '<img src="' + artwork.url + '" alt="' + escapeAttr(artwork.alt) + '" class="artwork-img" loading="lazy">' +
      '<p class="artwork-credit">' + artwork.credit + "</p>" +
      '<p class="artwork-note">' + artwork.note + "</p>" +
      "</div>"
    );
  }

  function hinataCtaBlock(type, result, code) {
    var buttons = result.presetQuestions.map(function (q, i) {
      return '<button type="button" class="preset-q" data-q="' + escapeAttr(q) + '">' + q + "</button>";
    }).join("");
    return (
      '<div class="section-block"><div class="hinata-cta-box">' +
      '<p class="lead">この結果、ヒナタと一緒にもう少し掘ってみませんか。<br>最初の1週間は無料で話せます。</p>' +
      '<p class="hinata-signup-note">🔰 まだヒナタAIにご登録がないかたは、LINEを開いたら表示される案内から先に無料トライアルにご登録ください。登録がお済みのかたは、そのまま下のボタンから相談できます。</p>' +
      buttons +
      '<button type="button" class="btn btn-line" id="hinata-free-talk">自由に相談する（LINEを開く）</button>' +
      '<p class="hinata-note">質問ボタンをタップすると、相談文をコピーしてLINEを開きます。トーク画面に貼り付けて送信してください。</p>' +
      "</div></div>"
    );
  }

  function wireHinataButtons(type, result) {
    var mbtiPrefix = state.mbtiType ? "【16Personalities: " + state.mbtiType + "】\n" : "";
    $result.querySelectorAll(".preset-q").forEach(function (btn) {
      btn.addEventListener("click", function () {
        var q = btn.getAttribute("data-q");
        copyText(q);
        toast("質問をコピーしました。LINEに貼り付けて送信してください");
        setTimeout(function () { window.open(HINATA_LINE_URL, "_blank"); }, 400);
      });
    });
    var freeBtn = document.getElementById("hinata-free-talk");
    if (freeBtn) {
      freeBtn.addEventListener("click", function () {
        if (mbtiPrefix) {
          copyText(mbtiPrefix.trim());
          toast("16Personalitiesタイプをコピーしました。LINEに貼り付けてから相談を始めてください");
          setTimeout(function () { window.open(HINATA_LINE_URL, "_blank"); }, 400);
        } else {
          window.open(HINATA_LINE_URL, "_blank");
        }
      });
    }
  }

  function retryBlock() {
    return (
      '<div class="section-block" style="text-align:center;">' +
      '<button type="button" class="btn btn-outline" id="retry-diagnose">もう一度診断する</button>' +
      "</div>"
    );
  }

  function wireRetryButton() {
    var retryBtn = document.getElementById("retry-diagnose");
    if (retryBtn) {
      retryBtn.addEventListener("click", function () {
        history.replaceState(null, "", location.pathname);
        startDiagnose();
      });
    }
  }

  function escapeAttr(str) {
    return str.replace(/"/g, "&quot;");
  }

  // ===== 初期化・ルーティング =====
  function init() {
    renderHome();

    document.getElementById("start-diagnose-btn").addEventListener("click", startDiagnose);

    var params = new URLSearchParams(location.search);
    var typeParam = params.get("type");
    if (typeParam && TYPES[typeParam]) {
      showResult(typeParam);
    } else {
      showScreen("home");
    }
  }

  document.addEventListener("DOMContentLoaded", init);
